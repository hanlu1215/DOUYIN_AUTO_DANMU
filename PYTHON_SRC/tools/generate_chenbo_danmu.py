def _find_project_root(start):
    """向上最多找 4 层，定位含 danmu/ 的项目根目录（本文件位于 PYTHON_SRC/tools/ 下）。"""
    d = start
    for _ in range(4):
        if os.path.isdir(os.path.join(d, "danmu")):
            return d
        nd = os.path.dirname(d)
        if nd == d:
            break
        d = nd
    return start


