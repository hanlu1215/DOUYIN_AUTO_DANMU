def main():
    pool = build_pool()
    handwritten = list(dict.fromkeys(HANDWRITTEN))   # 去重保序，全部保留
    rest = sorted(m for m in pool if m not in set(handwritten))
    random.shuffle(rest)

    take = max(0, TARGET - len(handwritten))
    result = handwritten + rest[:take]
    random.shuffle(result)

    if len(result) < TARGET:
        print("注意：候选池不足，仅生成 %d 条" % len(result))

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    save_danmu(OUT_PATH, result)
    assert len(result) == len(set(result)), "存在重复条目！"
    print("已生成 %d 条不重复弹幕 -> %s" % (len(result), OUT_PATH))
    print("示例：")
    for m in result[:8]:
        print("  " + m)


if __name__ == "__main__":
    main()
